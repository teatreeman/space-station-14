namespace Content.Client._Starlight.Cargo.Exchange;

/// <summary>
/// The Guild Exchange terminal: a watchlist, a candle chart, order entry, the account's portfolio, and the news wire,
/// earnings calendar and trade tape. Every time on it is station time.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GuildExchangeWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IGameTiming _timing = default!;

    private static readonly Color Amber = Color.FromHex("#ffb000");
    private static readonly Color Up = Color.FromHex("#3fd16a");
    private static readonly Color Down = Color.FromHex("#e0504a");
    private static readonly Color Dim = Color.FromHex("#9a8a60");
    private static readonly Color Text = Color.FromHex("#d8cfa8");

    public event Action<string>? OnSelectCompany;
    public event Action<string, ExchangeOrderSide, ExchangeOrderType, int, float>? OnOrder;
    public event Action<int>? OnCancelOrder;
    public event Action<ExchangeAccountKind>? OnSelectAccount;
    public event Action<bool>? OnFullBudget;
    public event Action? OnWithdraw;

    private GuildExchangeBuiState? _market;
    private GuildExchangeAccountMessage? _account;
    private string? _selected;
    private ExchangeOrderSide _side = ExchangeOrderSide.Buy;
    private ExchangeOrderType _type = ExchangeOrderType.Market;
    private TimeSpan _chartLast;
    private TimeSpan _chartInterval = TimeSpan.FromSeconds(30);

    private string _tape = string.Empty;
    private int _tapeOffset;
    private float _tapeTimer;

    public GuildExchangeWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Background.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#0b0d0a") };
        foreach (var label in new[] { BrandLabel, MarketsTitle, OrderTitle, PortfolioTitle, CompanyTitle })
        {
            label.FontColorOverride = Amber;
        }

        foreach (var label in new[] { LicenceLabel, MottoLabel, CompanyInfo, WatchHeader, PositionsHeader, CostsLabel, ChartStart, ChartEnd, RangeLabel })
        {
            label.FontColorOverride = Dim;
        }

        TickerLabel.FontColorOverride = Amber;
        ClockLabel.FontColorOverride = Amber;
        QuoteLabel.FontColorOverride = Text;
        EstimateLabel.FontColorOverride = Text;

        SideTabs.SetTabTitle(0, Loc.GetString("guild-exchange-window-wire"));
        SideTabs.SetTabTitle(1, Loc.GetString("guild-exchange-window-calendar"));
        SideTabs.SetTabTitle(2, Loc.GetString("guild-exchange-window-tape"));

        SideBuy.OnPressed += _ => SetSide(ExchangeOrderSide.Buy);
        SideSell.OnPressed += _ => SetSide(ExchangeOrderSide.Sell);
        SideShort.OnPressed += _ => SetSide(ExchangeOrderSide.Short);
        SideCover.OnPressed += _ => SetSide(ExchangeOrderSide.Cover);
        TypeMarket.OnPressed += _ => SetType(ExchangeOrderType.Market);
        TypeLimit.OnPressed += _ => SetType(ExchangeOrderType.Limit);
        Tf1.OnPressed += _ => SetTimeframe(1);
        Tf5.OnPressed += _ => SetTimeframe(5);
        Tf10.OnPressed += _ => SetTimeframe(10);
        AverageButton.OnToggled += args =>
        {
            Chart.ShowAverage = args.Pressed;
        };

        QtyEdit.OnTextChanged += _ => UpdateEstimate();
        PriceEdit.OnTextChanged += _ => UpdateEstimate();
        MaxButton.OnPressed += _ => QtyEdit.Text = MaxShares().ToString();
        SubmitOrder.OnPressed += _ => Submit();
        CommandLine.OnTextEntered += args => RunCommand(args.Text);

        PersonalButton.OnPressed += _ => OnSelectAccount?.Invoke(ExchangeAccountKind.Personal);
        CargoButton.OnPressed += _ => OnSelectAccount?.Invoke(ExchangeAccountKind.Cargo);
        FullBudgetButton.OnToggled += args => OnFullBudget?.Invoke(args.Pressed);
        WithdrawButton.OnPressed += _ => OnWithdraw?.Invoke();

        AverageButton.Pressed = true;
        SetSide(ExchangeOrderSide.Buy);
        SetType(ExchangeOrderType.Market);
        SetTimeframe(1);
    }

    private string Clock(TimeSpan time)
    {
        return ExchangeTime.Format(_entMan.System<SharedTimeSystem>(), time);
    }

    private ExchangeCompanyState? Selected => _market?.Companies.FirstOrDefault(c => c.Id == _selected);

    public void UpdateMarket(GuildExchangeBuiState state)
    {
        _market = state;
        if (_selected == null && state.Companies.Count > 0)
            Select(state.Companies[0].Id);

        RebuildWatchlist();
        RebuildTape();
        RefreshCompany();
        RebuildNews();
        RebuildCalendar();
        RebuildTrades();
        CostsLabel.Text = Loc.GetString("guild-exchange-window-costs",
            ("fee", (state.Fee * 100f).ToString("0.##")),
            ("borrow", (state.BorrowFee * 100f).ToString("0.###")),
            ("margin", (state.ShortMargin * 100f).ToString("0")));
        UpdateEstimate();
    }

    public void UpdateAccount(GuildExchangeAccountMessage account)
    {
        _account = account;

        PersonalButton.Pressed = account.Kind == ExchangeAccountKind.Personal;
        CargoButton.Pressed = account.Kind == ExchangeAccountKind.Cargo;
        CargoButton.Visible = account.CanTradeCargo;
        WithdrawButton.Visible = account.Kind == ExchangeAccountKind.Personal && account.HasId;
        FullBudgetButton.Visible = account.Kind == ExchangeAccountKind.Cargo && account.CanUnlockFullBudget;
        FullBudgetButton.Pressed = account.FullBudget;

        CashLabel.Text = account.Kind == ExchangeAccountKind.Cargo
            ? Loc.GetString("guild-exchange-window-budget", ("cash", account.Cash))
            : account.HasId
                ? Loc.GetString("guild-exchange-window-cash", ("cash", account.Cash))
                : Loc.GetString("guild-exchange-window-no-id");
        CapLabel.Text = account.FullBudget
            ? Loc.GetString("guild-exchange-window-full-budget-on")
            : account.CapLeft is { } cap
                ? Loc.GetString("guild-exchange-window-cap", ("cap", cap))
                : Loc.GetString("guild-exchange-window-deposit-hint");

        var total = account.Realised + account.Unrealised;
        PnlLabel.Text = Loc.GetString("guild-exchange-window-pnl", ("realised", account.Realised), ("open", account.Unrealised));
        PnlLabel.FontColorOverride = total >= 0 ? Up : Down;

        RebuildPositions();
        RebuildOrders();
        ShowNotice(account.Notice);
        UpdateEstimate();
    }

    public void UpdateChart(GuildExchangeChartMessage chart)
    {
        if (chart.Company != _selected)
            return;

        _chartLast = chart.LastTime;
        _chartInterval = chart.Interval;
        Chart.SetCandles(chart.Candles);
        RefreshChartLabels();
    }

    private void Select(string company)
    {
        _selected = company;
        Chart.SetCandles(Array.Empty<ExchangeCandle>());
        PriceEdit.Text = Selected is { } state ? state.Price.ToString("0.00") : string.Empty;
        OnSelectCompany?.Invoke(company);
        RefreshCompany();
        RebuildWatchlist();
        UpdateEstimate();
    }

    private void RefreshCompany()
    {
        if (Selected is not { } company)
            return;

        var change = company.Price / company.Open - 1f;
        CompanyTitle.Text = Loc.GetString("guild-exchange-window-company-title", ("ticker", company.Ticker), ("name", company.Name),
            ("sector", company.Sector));
        CompanyInfo.Text = company.Description;
        QuoteLabel.Text = Loc.GetString("guild-exchange-window-quote",
            ("last", company.Price.ToString("0.00")),
            ("bid", company.Bid.ToString("0.00")),
            ("ask", company.Ask.ToString("0.00")),
            ("change", Percent(change)),
            ("volume", Volume(company.Volume)));
        QuoteLabel.FontColorOverride = change >= 0 ? Up : Down;
        Chart.Reference = company.Open;
    }

    private void RefreshChartLabels()
    {
        if (Chart.Candles.Count == 0)
        {
            ChartStart.Text = ChartEnd.Text = RangeLabel.Text = string.Empty;
            return;
        }

        var (low, high) = Chart.Range();
        RangeLabel.Text = Loc.GetString("guild-exchange-window-range", ("high", high.ToString("0.00")), ("low", low.ToString("0.00")));
        ChartStart.Text = Clock(_chartLast - _chartInterval * Chart.Candles.Count);
        ChartEnd.Text = Clock(_chartLast);
    }

    private void RebuildWatchlist()
    {
        Watchlist.RemoveAllChildren();
        if (_market == null)
            return;

        foreach (var company in _market.Companies)
        {
            var change = company.Price / company.Open - 1f;
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            var button = new Button
            {
                Name = $"Watch{company.Ticker}",
                Text = $"{company.Ticker,-5}{company.Bid,7:0.00}{company.Ask,7:0.00}{Percent(change),7}",
                ToggleMode = true,
                Pressed = company.Id == _selected,
                HorizontalExpand = true,
            };
            button.Label.StyleClasses.Add("monospace");
            button.Label.Align = Label.AlignMode.Left;
            button.Label.FontColorOverride = change >= 0 ? Up : Down;
            var id = company.Id;
            button.OnPressed += _ => Select(id);

            row.AddChild(button);
            row.AddChild(new ExchangeChart { Points = company.Spark, Reference = company.Open, MinSize = new(30, 22) });
            Watchlist.AddChild(row);
        }
    }

    private void RebuildTape()
    {
        if (_market == null)
            return;

        _tape = string.Join("   ", _market.Companies.Select(c =>
        {
            var change = c.Price / c.Open - 1f;
            return $"{c.Ticker} {c.Price:0.00} {(change >= 0 ? "▲" : "▼")}{Percent(change)}";
        })) + "   ";
        _tapeOffset %= Math.Max(1, _tape.Length);
    }

    private void RebuildNews()
    {
        NewsList.RemoveAllChildren();
        if (_market == null)
            return;

        if (_market.News.Count == 0)
        {
            NewsList.AddChild(new Label { Text = Loc.GetString("guild-exchange-window-no-news"), FontColorOverride = Dim });
            return;
        }

        foreach (var news in _market.News)
        {
            var message = new FormattedMessage();
            message.PushColor(Dim);
            message.AddText(Clock(news.Time) + " ");
            message.Pop();
            if (news.Ticker != null)
            {
                message.PushColor(Amber);
                message.AddText($"[{news.Ticker}] ");
                message.Pop();
            }

            message.PushColor(Text);
            message.AddText(news.Text);
            message.Pop();
            if (news.Unconfirmed)
            {
                message.PushColor(Down);
                message.AddText(" " + Loc.GetString("guild-exchange-window-unconfirmed"));
                message.Pop();
            }

            var label = new RichTextLabel();
            label.SetMessage(message);
            NewsList.AddChild(label);
        }
    }

    private void RebuildCalendar()
    {
        CalendarList.RemoveAllChildren();
        if (_market == null)
            return;

        foreach (var entry in _market.Calendar)
        {
            string text;
            var color = Text;
            if (entry.Dividend)
            {
                text = Loc.GetString("guild-exchange-window-calendar-dividend", ("time", Clock(entry.Time)), ("ticker", entry.Ticker),
                    ("amount", entry.Amount.ToString("0.00")));
            }
            else if (entry.Actual is { } actual)
            {
                text = Loc.GetString("guild-exchange-window-calendar-reported", ("time", Clock(entry.Time)), ("ticker", entry.Ticker),
                    ("actual", actual.ToString("0.00")), ("consensus", entry.Consensus.ToString("0.00")));
                color = actual >= entry.Consensus ? Up : Down;
            }
            else
            {
                text = Loc.GetString("guild-exchange-window-calendar-earnings", ("time", Clock(entry.Time)), ("ticker", entry.Ticker),
                    ("consensus", entry.Consensus.ToString("0.00")));
            }

            var label = new Label { Text = text, FontColorOverride = color };
            label.StyleClasses.Add("monospace");
            CalendarList.AddChild(label);
        }
    }

    private void RebuildTrades()
    {
        TradeList.RemoveAllChildren();
        if (_market == null)
            return;

        if (_market.Trades.Count == 0)
        {
            TradeList.AddChild(new Label { Text = Loc.GetString("guild-exchange-window-no-trades"), FontColorOverride = Dim });
            return;
        }

        foreach (var trade in _market.Trades)
        {
            var label = new Label { Text = $"{Clock(trade.Time)} {trade.Text}", FontColorOverride = Text, ClipText = true };
            TradeList.AddChild(label);
        }
    }

    private void RebuildPositions()
    {
        Positions.RemoveAllChildren();
        if (_account == null || _market == null)
            return;

        if (_account.Longs.Count == 0 && _account.Shorts.Count == 0)
        {
            Positions.AddChild(new Label { Text = Loc.GetString("guild-exchange-window-no-positions"), FontColorOverride = Dim });
            return;
        }

        foreach (var held in _account.Longs)
        {
            if (_market.Companies.FirstOrDefault(c => c.Id == held.Company) is not { } company)
                continue;

            var average = held.Cost / (float) Math.Max(1, held.Shares);
            var pnl = (long) (company.Bid * held.Shares) - held.Cost;
            var pct = pnl / (float) Math.Max(1, held.Cost);
            AddPositionRow($"{company.Ticker,-5}{held.Shares,5}{average,8:0.00}{pnl,8}{Percent(pct),7}", pnl >= 0 ? Up : Down);
        }

        foreach (var held in _account.Shorts)
        {
            if (_market.Companies.FirstOrDefault(c => c.Id == held.Company) is not { } company)
                continue;

            var average = held.Proceeds / (float) Math.Max(1, held.Shares);
            var pnl = held.Collateral - held.Margin - (long) (company.Ask * held.Shares);
            var pct = pnl / (float) Math.Max(1, held.Proceeds);
            AddPositionRow($"{company.Ticker,-5}{-held.Shares,5}{average,8:0.00}{pnl,8}{Percent(pct),7}", pnl >= 0 ? Up : Down);
            AddPositionRow(Loc.GetString("guild-exchange-window-health", ("health", held.Health.ToString("0.00")),
                ("call", _market.MaintenanceMargin.ToString("0.00"))),
                held.Health < _market.MaintenanceMargin + 0.15f ? Down : Amber);
        }
    }

    private void AddPositionRow(string text, Color color)
    {
        var label = new Label { Text = text, FontColorOverride = color, ClipText = true };
        label.StyleClasses.Add("monospace");
        Positions.AddChild(label);
    }

    private void RebuildOrders()
    {
        Orders.RemoveAllChildren();
        if (_account == null || _market == null)
            return;

        OrdersTitle.Text = Loc.GetString("guild-exchange-window-orders", ("count", _account.Orders.Count), ("max", _market.MaxOrders));
        foreach (var order in _account.Orders)
        {
            var ticker = _market.Companies.FirstOrDefault(c => c.Id == order.Company)?.Ticker ?? order.Company;
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            var label = new Label
            {
                Text = Loc.GetString(order.Buy ? "guild-exchange-window-order-buy" : "guild-exchange-window-order-sell",
                    ("shares", order.Shares), ("ticker", ticker), ("limit", order.Limit.ToString("0.00"))),
                FontColorOverride = Text,
                HorizontalExpand = true,
            };
            label.StyleClasses.Add("monospace");
            var cancel = new Button { Name = $"Cancel{order.Id}", Text = Loc.GetString("guild-exchange-window-cancel") };
            var id = order.Id;
            cancel.OnPressed += _ => OnCancelOrder?.Invoke(id);
            row.AddChild(label);
            row.AddChild(cancel);
            Orders.AddChild(row);
        }
    }

    private void SetSide(ExchangeOrderSide side)
    {
        _side = side;
        SideBuy.Pressed = side == ExchangeOrderSide.Buy;
        SideSell.Pressed = side == ExchangeOrderSide.Sell;
        SideShort.Pressed = side == ExchangeOrderSide.Short;
        SideCover.Pressed = side == ExchangeOrderSide.Cover;

        // Shorts and covers fill at the market only.
        if (side is ExchangeOrderSide.Short or ExchangeOrderSide.Cover)
            SetType(ExchangeOrderType.Market);
        TypeLimit.Disabled = side is ExchangeOrderSide.Short or ExchangeOrderSide.Cover;
        UpdateEstimate();
    }

    private void SetType(ExchangeOrderType type)
    {
        _type = type;
        TypeMarket.Pressed = type == ExchangeOrderType.Market;
        TypeLimit.Pressed = type == ExchangeOrderType.Limit;
        LimitRow.Visible = type == ExchangeOrderType.Limit;
        UpdateEstimate();
    }

    private void SetTimeframe(int ticks)
    {
        Tf1.Pressed = ticks == 1;
        Tf5.Pressed = ticks == 5;
        Tf10.Pressed = ticks == 10;
        Chart.Timeframe = ticks;
        Chart.Regroup();
        RefreshChartLabels();
    }

    private int Quantity()
    {
        return int.TryParse(QtyEdit.Text.Trim(), out var shares) ? shares : 0;
    }

    private float LimitPrice()
    {
        return float.TryParse(PriceEdit.Text.Trim(), System.Globalization.NumberStyles.Float,
            System.Globalization.CultureInfo.InvariantCulture, out var price) ? price : 0f;
    }

    private void UpdateEstimate()
    {
        if (Selected is not { } company || _market == null)
        {
            EstimateLabel.Text = string.Empty;
            return;
        }

        var shares = Quantity();
        var price = _type == ExchangeOrderType.Limit && LimitPrice() > 0f ? LimitPrice() : company.Price;
        var fee = _market.Fee;
        EstimateLabel.Text = _side switch
        {
            ExchangeOrderSide.Buy or ExchangeOrderSide.Cover => Loc.GetString("guild-exchange-window-estimate-cost",
                ("money", ExchangeMath.Buy(price, shares, company.Spread, fee))),
            ExchangeOrderSide.Sell => Loc.GetString("guild-exchange-window-estimate-proceeds",
                ("money", ExchangeMath.Sell(price, shares, company.Spread, fee))),
            _ => Loc.GetString("guild-exchange-window-estimate-short",
                ("margin", (long) MathF.Ceiling(_market.ShortMargin * price * shares)),
                ("money", ExchangeMath.Sell(price, shares, company.Spread, fee))),
        };
    }

    private int MaxShares()
    {
        if (Selected is not { } company || _account == null || _market == null)
            return 0;

        var budget = _account.CapLeft is { } cap ? Math.Min(cap, _account.Cash) : _account.Cash;
        return _side switch
        {
            ExchangeOrderSide.Buy => ExchangeMath.MaxAffordable(company.Price, budget, company.Spread, _market.Fee),
            ExchangeOrderSide.Sell => _account.Longs.FirstOrDefault(l => l.Company == company.Id)?.Shares ?? 0,
            ExchangeOrderSide.Cover => _account.Shorts.FirstOrDefault(s => s.Company == company.Id)?.Shares ?? 0,
            _ => (int) Math.Max(0, Math.Floor(Math.Min(_account.Cash / (double) (_market.ShortMargin * company.Price),
                (_account.CapLeft ?? long.MaxValue) / (double) company.Price))),
        };
    }

    private void Submit()
    {
        if (_selected == null)
            return;

        var shares = Quantity();
        if (shares <= 0)
        {
            ShowNotice(Loc.GetString("guild-exchange-window-bad-qty"));
            return;
        }

        OnOrder?.Invoke(_selected, _side, _type, shares, _type == ExchangeOrderType.Limit ? LimitPrice() : 0f);
    }

    /// <summary>
    /// The command line: "DONK &lt;GO&gt;" picks a company, "BUY 10 &lt;GO&gt;" or "SHORT 5 NT &lt;GO&gt;" sends a market order.
    /// </summary>
    private void RunCommand(string text)
    {
        CommandLine.Text = string.Empty;
        if (_market == null)
            return;

        var words = text.ToUpperInvariant().Replace("<GO>", " ")
            .Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Where(w => w != "GO")
            .ToList();
        if (words.Count == 0)
            return;

        if (words[0] == "HELP")
        {
            ShowNotice(Loc.GetString("guild-exchange-window-help"));
            return;
        }

        if (_market.Companies.FirstOrDefault(c => c.Ticker == words[0]) is { } named)
        {
            Select(named.Id);
            return;
        }

        ExchangeOrderSide? side = words[0] switch
        {
            "BUY" => ExchangeOrderSide.Buy,
            "SELL" => ExchangeOrderSide.Sell,
            "SHORT" => ExchangeOrderSide.Short,
            "COVER" => ExchangeOrderSide.Cover,
            _ => null,
        };

        if (side is not { } chosen)
        {
            ShowNotice(Loc.GetString("guild-exchange-window-unknown-command"));
            return;
        }

        if (words.Count > 2 && _market.Companies.FirstOrDefault(c => c.Ticker == words[2]) is { } target)
            Select(target.Id);

        SetSide(chosen);
        SetType(ExchangeOrderType.Market);
        QtyEdit.Text = words.Count > 1 && words[1] is "ALL" or "MAX" ? MaxShares().ToString()
            : words.Count > 1 ? words[1] : QtyEdit.Text;
        Submit();
    }

    private void ShowNotice(string? text)
    {
        var message = new FormattedMessage();
        if (!string.IsNullOrEmpty(text))
        {
            message.PushColor(Down);
            message.AddText(text);
            message.Pop();
        }

        NoticeLabel.SetMessage(message);
    }

    private static string Percent(float change)
    {
        return (change >= 0 ? "+" : "") + (change * 100f).ToString("0.0") + "%";
    }

    private static string Volume(float volume)
    {
        return volume >= 1000f ? (volume / 1000f).ToString("0.0") + "k" : volume.ToString("0");
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        ClockLabel.Text = Loc.GetString("guild-exchange-window-clock", ("time", Clock(_timing.CurTime)));

        if (_tape.Length == 0)
            return;

        _tapeTimer += args.DeltaSeconds;
        if (_tapeTimer < 0.15f)
            return;

        // Scroll the ticker one character at a time.
        _tapeTimer = 0;
        _tapeOffset = (_tapeOffset + 1) % _tape.Length;
        TickerLabel.Text = _tape[_tapeOffset..] + _tape[.._tapeOffset];
    }
}
