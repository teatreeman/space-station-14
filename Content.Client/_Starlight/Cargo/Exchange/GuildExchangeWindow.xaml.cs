using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Cargo.Exchange;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.Cargo.Exchange;

/// <summary>
/// The Guild Exchange screen: ticker, markets, the selected company's chart and order buttons, the account in use,
/// the news wire and recent trades.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GuildExchangeWindow : FancyWindow
{
    private static readonly Color Amber = Color.FromHex("#ffb000");
    private static readonly Color Up = Color.FromHex("#3fd16a");
    private static readonly Color Down = Color.FromHex("#e0504a");
    private static readonly Color Dim = Color.FromHex("#9a8a60");
    private static readonly int[] OrderSizes = [1, 5, 25];

    /// <summary>
    /// Buy (positive) or sell (negative) shares of a company.
    /// </summary>
    public event Action<string, int>? OnTrade;

    public event Action<ExchangeAccountKind>? OnSelectAccount;

    /// <summary>
    /// Unlock (true) or lock (false) the whole cargo budget.
    /// </summary>
    public event Action<bool>? OnFullBudget;
    public event Action? OnWithdraw;

    private GuildExchangeBuiState? _market;
    private GuildExchangeAccountMessage? _account;
    private string? _selected;

    private string _tape = string.Empty;
    private int _tapeOffset;
    private float _tapeTimer;

    public GuildExchangeWindow()
    {
        RobustXamlLoader.Load(this);
        Background.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#0b0d0a") };

        foreach (var label in new[] { TickerLabel, WatchlistTitle, PortfolioTitle, NewsTitle, TradesTitle, CompanyTitle })
        {
            label.FontColorOverride = Amber;
        }

        MottoLabel.FontColorOverride = Dim;
        CompanyInfo.FontColorOverride = Dim;
        HaltLabel.FontColorOverride = Down;

        PersonalButton.OnPressed += _ => OnSelectAccount?.Invoke(ExchangeAccountKind.Personal);
        CargoButton.OnPressed += _ => OnSelectAccount?.Invoke(ExchangeAccountKind.Cargo);
        WithdrawButton.OnPressed += _ => OnWithdraw?.Invoke();
        FullBudgetButton.OnToggled += args => OnFullBudget?.Invoke(args.Pressed);

        foreach (var size in OrderSizes)
        {
            AddOrderButton(BuyButtons, $"Buy{size}", Loc.GetString("guild-exchange-window-buy", ("shares", size)), () => size);
            AddOrderButton(SellButtons, $"Sell{size}", Loc.GetString("guild-exchange-window-sell", ("shares", size)), () => -size);
        }

        AddOrderButton(BuyButtons, "BuyMax", Loc.GetString("guild-exchange-window-buy", ("shares", Loc.GetString("guild-exchange-window-max"))), MaxBuy);
        AddOrderButton(SellButtons, "SellAll", Loc.GetString("guild-exchange-window-sell", ("shares", Loc.GetString("guild-exchange-window-all"))), () => -Held());
    }

    private void AddOrderButton(BoxContainer row, string name, string text, Func<int> shares)
    {
        var button = new Button { Name = name, Text = text, HorizontalExpand = true };
        button.OnPressed += _ =>
        {
            var amount = shares();
            if (_selected != null && amount != 0)
                OnTrade?.Invoke(_selected, amount);
        };
        row.AddChild(button);
    }

    public void UpdateMarket(GuildExchangeBuiState state)
    {
        _market = state;
        if (_selected == null || state.Companies.All(c => c.Id != _selected))
            _selected = state.Companies.FirstOrDefault()?.Id;

        _tape = string.Join("   ", state.Companies.Select(c =>
            $"{c.Ticker} {c.Price:0.00} {(c.Price >= c.Open ? "▲" : "▼")}{Change(c.Price, c.Open)}")) + "   ";
        HaltLabel.Visible = state.Halted;

        RebuildWatchlist();
        RefreshSelected();
        RebuildNews();
        RebuildTrades();
        RefreshAccount();
    }

    public void UpdateAccount(GuildExchangeAccountMessage account)
    {
        _account = account;
        RefreshSelected();
        RefreshAccount();
    }

    private void RebuildWatchlist()
    {
        Watchlist.RemoveAllChildren();
        if (_market == null)
            return;

        foreach (var company in _market.Companies)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            var button = new Button
            {
                Name = $"Watch{company.Ticker}",
                Text = $"{company.Ticker,-5} {company.Price,8:0.00}  {Change(company.Price, company.Open)}",
                HorizontalExpand = true,
                ToggleMode = true,
                Pressed = company.Id == _selected,
            };
            button.Label.FontColorOverride = company.Price >= company.Open ? Up : Down;
            var id = company.Id;
            button.OnPressed += _ =>
            {
                _selected = id;
                RebuildWatchlist();
                RefreshSelected();
            };
            row.AddChild(button);
            row.AddChild(new ExchangeChart { Points = company.History, Reference = company.Open, MinSize = new(60, 24) });
            Watchlist.AddChild(row);
        }
    }

    private void RefreshSelected()
    {
        var company = Selected();
        if (company == null || _market == null)
            return;

        CompanyTitle.Text = $"{company.Ticker} · {company.Name} · {company.Price:0.00} ({Change(company.Price, company.Open)})";
        CompanyInfo.Text = $"{company.Sector}. {company.Description}";
        Chart.Points = company.History;
        Chart.Reference = company.Open;

        var buy = ExchangeMath.Buy(company.Price, 1, company.Liquidity, _market.Spread, _market.Fee).Cost;
        var sell = ExchangeMath.Sell(company.Price, 1, company.Liquidity, _market.Spread, _market.Fee).Proceeds;
        QuoteLabel.Text = Loc.GetString("guild-exchange-window-quote",
            ("buy", buy), ("sell", sell), ("fee", MathF.Round(_market.Fee * 100f, 1)));
    }

    private void RefreshAccount()
    {
        if (_account is not { } account)
            return;

        PersonalButton.Pressed = account.Kind == ExchangeAccountKind.Personal;
        CargoButton.Pressed = account.Kind == ExchangeAccountKind.Cargo;
        CargoButton.Visible = account.CanTradeCargo;
        WithdrawButton.Visible = account.Kind == ExchangeAccountKind.Personal && account.HasId;
        FullBudgetButton.Visible = account.Kind == ExchangeAccountKind.Cargo && account.CanUnlockFullBudget;
        FullBudgetButton.Pressed = account.FullBudget;

        var tradable = account.Kind == ExchangeAccountKind.Cargo || account.HasId;
        foreach (var button in BuyButtons.Children.Concat(SellButtons.Children).OfType<Button>())
        {
            button.Disabled = !tradable;
        }

        CashLabel.Text = !tradable
            ? Loc.GetString("guild-exchange-window-no-id")
            : Loc.GetString(account.Kind == ExchangeAccountKind.Cargo ? "guild-exchange-window-budget" : "guild-exchange-window-cash",
                ("cash", account.Cash));
        CapLabel.Text = account.FullBudget
            ? Loc.GetString("guild-exchange-window-full-budget-on")
            : account.CapLeft is { } cap
                ? Loc.GetString("guild-exchange-window-cap", ("cap", cap))
                : Loc.GetString("guild-exchange-window-deposit-hint");
        ProfitLabel.Text = Loc.GetString("guild-exchange-window-profit", ("profit", account.Profit));
        ProfitLabel.FontColorOverride = account.Profit >= 0 ? Up : Down;

        NoticeLabel.Text = account.Notice ?? string.Empty;
        NoticeLabel.FontColorOverride = Down;

        Holdings.RemoveAllChildren();
        if (account.Holdings.Count == 0)
        {
            Holdings.AddChild(new Label { Text = Loc.GetString("guild-exchange-window-no-holdings"), FontColorOverride = Dim });
            return;
        }

        foreach (var holding in account.Holdings)
        {
            var company = _market?.Companies.FirstOrDefault(c => c.Id == holding.Company);
            if (company == null)
                continue;

            var value = (int) (company.Price * holding.Shares);
            Holdings.AddChild(new Label
            {
                Text = Loc.GetString("guild-exchange-window-holding",
                    ("ticker", company.Ticker),
                    ("shares", holding.Shares),
                    ("avg", (holding.Cost / (float) holding.Shares).ToString("0.00")),
                    ("value", value),
                    ("change", Change(value, holding.Cost))),
                FontColorOverride = value >= holding.Cost ? Up : Down,
            });
        }
    }

    private void RebuildNews()
    {
        NewsList.RemoveAllChildren();
        if (_market == null || _market.News.Count == 0)
        {
            NewsList.AddChild(new Label { Text = Loc.GetString("guild-exchange-window-no-news"), FontColorOverride = Dim });
            return;
        }

        foreach (var news in _market.News)
        {
            var tag = news.Unconfirmed ? $" [{Loc.GetString("guild-exchange-window-unconfirmed")}]" : string.Empty;
            NewsList.AddChild(new Label
            {
                Text = $"{news.Time:hh\\:mm} {news.Ticker}{tag}",
                FontColorOverride = news.Unconfirmed ? Dim : Amber,
            });
            var body = new RichTextLabel { HorizontalExpand = true };
            body.SetMessage(FormattedMessage.FromUnformatted(news.Text));
            NewsList.AddChild(body);
        }
    }

    private void RebuildTrades()
    {
        TradeList.RemoveAllChildren();
        if (_market == null || _market.Trades.Count == 0)
        {
            TradeList.AddChild(new Label { Text = Loc.GetString("guild-exchange-window-no-trades"), FontColorOverride = Dim });
            return;
        }

        foreach (var trade in _market.Trades)
        {
            TradeList.AddChild(new Label { Text = trade, FontColorOverride = Dim, ClipText = true });
        }
    }

    private ExchangeCompanyState? Selected() => _market?.Companies.FirstOrDefault(c => c.Id == _selected);

    private int Held() => _account?.Holdings.FirstOrDefault(h => h.Company == _selected)?.Shares ?? 0;

    private int MaxBuy()
    {
        if (Selected() is not { } company || _market == null || _account == null)
            return 0;

        var budget = _account.CapLeft is { } cap ? Math.Min(cap, _account.Cash) : _account.Cash;
        return ExchangeMath.MaxAffordable(company.Price, budget, company.Liquidity, _market.Spread, _market.Fee);
    }

    private static string Change(float now, float then)
    {
        if (then <= 0)
            return "0.0%";

        var change = (now - then) / then * 100f;
        return $"{(change >= 0 ? "+" : string.Empty)}{change:0.0}%";
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_tape.Length == 0)
            return;

        _tapeTimer += args.DeltaSeconds;
        if (_tapeTimer < 0.15f)
            return;

        // Scroll the ticker one character at a time.
        _tapeTimer = 0;
        _tapeOffset = (_tapeOffset + 1) % _tape.Length;
        TickerLabel.Text = _tape[_tapeOffset..] + _tape[.._tapeOffset];
    }
}
