using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Chemistry;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Starlight.Chemistry.UI;

/// <summary>
/// The smoke machine's panel: power switch, purge, puff size and what's in the tank.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SmokeMachineWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;

    public event Action? OnToggle;
    public event Action<int>? OnSetting;
    public event Action? OnPurge;

    public SmokeMachineWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ToggleButton.OnPressed += _ => OnToggle?.Invoke();
        PurgeButton.OnPressed += _ => OnPurge?.Invoke();
    }

    public void UpdateState(SmokeMachineBoundUserInterfaceState state)
    {
        ToggleButton.Text = Loc.GetString(state.Enabled ? "smoke-machine-window-turn-off" : "smoke-machine-window-turn-on");
        ToggleButton.Pressed = state.Enabled;
        PurgeButton.Disabled = state.Volume <= 0;

        if (SettingButtons.ChildCount != state.MaxSetting)
        {
            SettingButtons.RemoveAllChildren();
            for (var i = 1; i <= state.MaxSetting; i++)
            {
                var setting = i;
                var button = new Button { Text = SmokeMachinePuffs.Radius(setting).ToString(), ToggleMode = true, MinWidth = 40 };
                button.OnPressed += _ => OnSetting?.Invoke(setting);
                SettingButtons.AddChild(button);
            }
        }

        var index = 1;
        foreach (var child in SettingButtons.Children)
        {
            if (child is Button button)
                button.Pressed = index == state.Setting;
            index++;
        }

        TankLabel.Text = Loc.GetString("smoke-machine-window-tank", ("volume", state.Volume), ("max", state.MaxVolume));

        TankContents.RemoveAllChildren();
        if (state.Contents.Count == 0)
        {
            TankContents.AddChild(new Label { Text = Loc.GetString("smoke-machine-window-tank-empty"), StyleClasses = { "LabelSubText" } });
            return;
        }

        foreach (var entry in state.Contents)
        {
            if (!_proto.TryIndex(entry.Reagent, out var reagent))
                continue;

            TankContents.AddChild(new Label
            {
                Text = Loc.GetString("smoke-machine-window-reagent", ("reagent", reagent.LocalizedName), ("quantity", entry.Quantity)),
            });
        }
    }
}
